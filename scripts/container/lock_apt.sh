#!/usr/bin/env bash
# Regenerate the container's Ubuntu package locks for one platform (#42).
#
#   scripts/container/lock_apt.sh linux-x86_64|linux-aarch64
#
# Runs the pinned base image ([container].base_image) for that architecture and resolves,
# with `apt-get install -s`, exactly what each stage adds:
#   runtime: container/apt/runtime.txt
#   build:   the R .deb's Depends + container/apt/build.txt, on top of runtime
#   full:    LibreOffice's .deb Depends + container/apt/full.txt, on top of runtime
# and writes container/apt/lock-<platform>-<stage>.txt. container/apt/install.sh installs
# those versions and nothing else. Rerun it only to re-pin (for example when a locked
# version has left the archive), and review the diff.
set -euo pipefail
platform="${1:?usage: $0 linux-x86_64|linux-aarch64}"
case "$platform" in
  linux-x86_64) docker_platform=linux/amd64 ;;
  linux-aarch64) docker_platform=linux/arm64 ;;
  *) echo "unknown platform: $platform" >&2; exit 2 ;;
esac
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
args() { (cd "$REPO" && uv run --quiet python scripts/container_args.py "$@"); }
base="$(args build-args --platform "$platform" | sed -n 's/^--build-arg=BASE_IMAGE=//p')"

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
fetch() {
  read -r url sha file < <(args asset "$1" "$platform")
  curl -sSfL --retry 3 -o "$work/$file" "$url"
  echo "$sha  $work/$file" | shasum -a 256 -c --status || { echo "checksum mismatch: $file" >&2; exit 1; }
  echo "$file"
}
r_deb="$(fetch "ci.$platform.r")"
lo_tgz="$(fetch container.libreoffice)"
cp "$REPO"/container/apt/{runtime,build,full}.txt "$work/"

docker run --rm --platform "$docker_platform" -v "$work:/w" "$base" bash -euo pipefail -c '
  export DEBIAN_FRONTEND=noninteractive
  list() { grep -v "^#" "/w/$1.txt" | sed "/^$/d"; }
  # "Inst name [old] (version origin [arch])" -> name=version; the pinned .debs are excluded.
  sim() {
    apt-get install -s --no-install-recommends "$@" \
      | sed -n "s/^Inst \([^ ]*\) \(\[[^]]*\] \)\{0,1\}(\([^ ]*\) .*/\1=\3/p" \
      | grep -Ev "^(r-[0-9.]+|libreoffice[0-9.]*.*|libobasis[0-9.]*.*)=" | sort
  }
  apt-get update -qq
  sim $(list runtime) > /w/runtime.lock
  apt-get install -y -qq --no-install-recommends $(cat /w/runtime.lock) > /dev/null
  sim "/w/'"$r_deb"'" $(list build) > /w/build.lock
  mkdir /w/lo && tar -xzf "/w/'"$lo_tgz"'" -C /w/lo --strip-components=1
  sim /w/lo/DEBS/*.deb $(list full) > /w/full.lock
'
for stage in runtime build full; do
  out="$REPO/container/apt/lock-$platform-$stage.txt"
  {
    echo "# Generated by scripts/container/lock_apt.sh $platform from container/apt/$stage.txt."
    echo "# Base: $base"
    echo "# Do not edit; rerun the script to re-pin."
    cat "$work/$stage.lock"
  } > "$out"
  echo "$out: $(grep -vc '^#' "$out") packages"
done
